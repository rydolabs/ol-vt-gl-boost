import assert from 'node:assert/strict';
import {GeometryStore,StyleStore,DirtyTracker} from '../src/compat/core/stores.js';
import {RenderReferenceStore,RenderSchedule} from '../src/compat/core/schedule.js';
import {expandPackedPathOrder,RendererKernel} from '../src/compat/core/RendererKernel.js';
import {WebGLVectorRenderer} from '../src/compat/VectorRenderer.js';
const geo=new GeometryStore();
const inserted=geo.upsert('road',{kind:'line'});
assert.equal(inserted.created,true);assert.equal(geo.upsert('road',{kind:'line'}).id,inserted.id);
assert.equal(geo.get(inserted.id).version,2);
const styles=new StyleStore();
assert.equal(styles.intern({alpha:1,z:2}),styles.intern({z:2,alpha:1}));
const dirty=new DirtyTracker();
dirty.mark('road');assert.deepEqual(dirty.consume(),['road']);assert.equal(dirty.size,0);
const references=[{id:'line1',geometryId:1,styleId:1,geometryType:'line',order:0,visible:true,sceneLayerKey:'a',sceneLayerZIndex:0,sceneLayerSequence:0,sceneStyleZIndex:0}];
const store=new RenderReferenceStore(references);
assert.equal(store.getAll().length,1);
const version=store.version;
assert.equal(store.set(references.map(r=>({...r}))).size,0);
assert.equal(store.version,version);
const schedule=new RenderSchedule().build(references);
assert.equal(schedule.length,1);assert.equal(schedule[0].passes.line[0].id,'line1');
const expanded=expandPackedPathOrder([{id:'packed',geometryType:'line',order:5,packedPathInstanceCounts:[2,1],packedPathVertexCounts:[3,2]}]);
assert.deepEqual(expanded.map(x=>x.order),[5,6]);
assert.deepEqual(expanded.map(x=>x.packedPathStart),[0,2]);
assert.equal(typeof RendererKernel,'function');
assert.equal(typeof WebGLVectorRenderer,'function');
